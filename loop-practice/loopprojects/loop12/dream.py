def main() -> int:
    ap = argparse.ArgumentParser(description="Dreaming-Loop orchestrator")
    ap.add_argument("--init", action="store_true", help="scaffold loop12 files")
    ap.add_argument("--date", help="run one dreaming beat for this YYYY-MM-DD")
    ap.add_argument("--check", action="store_true", help="run the scan only")
    ap.add_argument("--show", action="store_true", help="print the dreaming state")
    ap.add_argument("--reset", action="store_true", help="clear NEEDS_HUMAN")
    ap.add_argument("--max-attempts", type=int, default=MAX_ATTEMPTS)
    args = ap.parse_args()

    if args.init:
        RUNS_DIR.mkdir(exist_ok=True)
        if not STATE_MD.exists():
            write_state(STATE_DEFAULTS)
        for p, txt in [(LOG_MD, None), (PROGRESS_MD, None), (COST_MD, None)]:
            if not p.exists():
                p.write_text("", encoding="utf-8")
        if not PROGRESS_MD.exists() or PROGRESS_MD.read_text().strip() == "":
            PROGRESS_MD.write_text(render_progress(read_state()), encoding="utf-8")
        if not LOG_MD.exists() or LOG_MD.read_text().strip() == "":
            LOG_MD.write_text(
                "# Loop log — Project 12 (The Dreaming Loop)\n\n"
                "| Run | Date | Result | What happened |\n"
                "|-----|------|--------|---------------|\n", encoding="utf-8")
        COST_MD.write_text(render_cost(), encoding="utf-8")
        print("loop12 scaffold ready. Next: python loop12/dream.py --date "
              "YYYY-MM-DD")
        return 0

    if args.show:
        st = read_state()
        print(json.dumps({k: v for k, v in st.items() if k != "ledger"},
                         indent=2, ensure_ascii=False))
        for row in st["ledger"]:
            print(f'  dream {row["run"]} {row["date"]} [{row["state"]}] '
                  f'{row["branch"]}: {row["what"]}')
        return 0

    if args.reset:
        st = read_state()
        st["state"] = "IDLE"; st["branch"] = "—"; st["proposal"] = "—"
        st["needs_human_note"] = ""
        write_state(st)
        print("reset -> IDLE")
        return 0

    if args.check:
        st = read_state()
        scan = run_scan(st["last_dream"], args.date or str(_date.today()))
        print(json.dumps(scan, indent=2, ensure_ascii=False))
        return 0

    if args.date:
        return run_beat(find_claude(), args.date, args.max_attempts)

    ap.print_help()
    return 0


if __name__ == "__main__":
    sys.exit(main())
