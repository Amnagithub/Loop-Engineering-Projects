def run_scan(after: str, until: str) -> dict:
    r = subprocess.run(
        [sys.executable, str(SCAN_PY), "--loop-root", str(LOOPPROJECTS),
         "--extra", str(OBSERVED), "--from", after, "--until", until, "--json"],
        capture_output=True, text=True, encoding="utf-8", errors="replace",
        timeout=120)
    if r.returncode != 0:
        raise RuntimeError("scan.py failed: " + (r.stderr or r.stdout)[:500])
    return json.loads(r.stdout)


