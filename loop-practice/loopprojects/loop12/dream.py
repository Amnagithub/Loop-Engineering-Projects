def git(args: list[str], cwd: Path = REPO_ROOT) -> str:
    r = subprocess.run(["git", "-C", str(cwd)] + args,
                       capture_output=True, text=True, encoding="utf-8",
                       errors="replace")
    return (r.stdout or "").strip()


def working_tree_clean() -> tuple[bool, str]:
    dirty = git(["status", "--porcelain"])
    if dirty:
        return False, dirty
    return True, ""


def find_claude() -> str:
    p = shutil.which("claude")
    if not p:
        sys.exit("dream.py: cannot find the `claude` CLI on PATH")
    return p


def run_agent(claude: str, prompt: str, out_json: Path, cwd: Path,
              allowed: str) -> dict:
    """Run one headless `claude -p` child; persist JSON + stderr.

    The prompt travels on STDIN, not as an argv element: prompts are long and
    full of embedded double quotes, and Python's Windows argv quoting mangles
    them so the child would see an empty prompt ("Input must be provided...").
    """
    cmd = [claude, "-p", "--output-format", "json",
           "--permission-mode", "acceptEdits",
           "--no-session-persistence",
           "--allowedTools", allowed]
    stderr_path = out_json.with_suffix(".stderr")
    try:
        proc = subprocess.run(cmd, input=prompt, capture_output=True,
                              text=True, encoding="utf-8", errors="replace",
                              timeout=1200, cwd=str(cwd), env=ENV)
    except subprocess.TimeoutExpired:
        return {"ok": False, "text": "", "usage": None,
                "err": "timed out after 1200s"}
    out_json.write_text(proc.stdout or "", encoding="utf-8")
    stderr_path.write_text(proc.stderr or "", encoding="utf-8")
    try:
        j = json.loads(proc.stdout) if proc.stdout.strip() else {}
    except json.JSONDecodeError as e:
        return {"ok": False, "text": proc.stdout, "usage": None,
                "err": f"child did not return JSON: {e}"}
    text = j.get("result") or ""
    usage = j.get("usage") or {}
    return {
        "ok": not j.get("is_error", False) and bool(text),
        "text": text,
        "usage": {"input": usage.get("input_tokens", 0),
                  "output": usage.get("output_tokens", 0),
                  "cache_read": usage.get("cache_read_input_tokens", 0)},
        "err": "",
    }


def make_snapshot() -> Path:
    """Materialise HEAD into a throwaway dir under .loop12-beats (git-ignored,
    INSIDE the trusted repo tree so a headless child never stalls on the
    folder-trust prompt); return the beat dir (snapshot is <dir>/snapshot)."""
    BEATS_DIR.mkdir(exist_ok=True)
    tmp = Path(tempfile.mkdtemp(prefix="dream-", dir=str(BEATS_DIR)))
    snap = tmp / "snapshot"
    snap.mkdir()
    arc = subprocess.run(["git", "-C", str(REPO_ROOT), "archive", "--format=tar",
                          "HEAD"], capture_output=True)
    if arc.returncode != 0:
        shutil.rmtree(tmp, ignore_errors=True)
        sys.exit("dream.py: git archive HEAD failed: "
                 + arc.stderr.decode("utf-8", "replace"))
    with tarfile.open(fileobj=io.BytesIO(arc.stdout), mode="r:") as tar:
        tar.extractall(snap)
    return tmp


