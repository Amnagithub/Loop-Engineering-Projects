def load_skill(name: str) -> str:
    return (LOOP12 / "skills" / name).read_text(encoding="utf-8")


def dreamer_prompt(run: int, scan_path: Path, proposal_path: Path,
                   attempt: int, feedback: str = "") -> str:
    skill = load_skill("dreamer-skill.md")
    prompt = (skill.replace("<scan_path>", str(scan_path))
              .replace("<proposal_path>", str(proposal_path))
              .replace("<run>", str(run)))
    if feedback:
        prompt += ("\n\n## Your previous draft FAILED the Checker\n\n"
                   "The Checker's reasons, verbatim:\n\n" + feedback +
                   "\n\nFix exactly those defects and rewrite the proposal file "
                   "(overwrite it). Keep everything the Checker accepted intact.\n")
    return prompt


def checker_prompt(scan_path: Path, proposal_path: Path) -> str:
    skill = load_skill("checker-skill.md")
    return (skill.replace("<scan_path>", str(scan_path))
            .replace("<proposal_path>", str(proposal_path)))


def parse_verdict(text: str) -> str:
    m = re.search(r"VERDICT:\s*(PASS|FAIL)", text)
    return m.group(1) if m else "FAIL"


# --------------------------------------------------------------------------- #
# proposal application (the ONLY place the repo's rules change)
# --------------------------------------------------------------------------- #

def _resolve_skills(p: str) -> Path:
    p2 = p.replace("\\", "/").rstrip("/")
    if not p2.startswith(SKILLS_REL + "/") and p2 != SKILLS_REL:
        raise ValueError(f"proposal path outside the skills corpus: {p2}")
    return REPO_ROOT / p2


def pr_markdown(draft: dict) -> str:
    pr = draft.get("pr", {})
    title = (pr.get("title") or "dream: smallest rule improvement").strip()
    body = pr.get("body") or draft.get("summary", "")
    return f"# {title}\n\n{body}\n"


def apply_proposal(draft: dict, run: int) -> str:
    """Commit the reviewed proposal to claude/dream-<run>. Returns branch name.
    Touches ONLY the skills corpus + loop12/proposals. Never main, never push."""
    rule = draft.get("rule_change", {})
    dele = draft.get("deletion", {})
    if rule.get("action") not in ("add", "edit"):
        raise ValueError("rule_change.action must be add|edit")
    rule_path = _resolve_skills(rule["path"])
    delete_path = _resolve_skills(dele["path"]) if dele.get("path") else None
    if delete_path == rule_path:
        raise ValueError("deletion targets the same file as the rule change")

    branch = f"claude/dream-{run}"
    git(["checkout", "-b", branch])
    try:
        if rule["action"] == "add":
            if rule_path.exists():
                raise ValueError(f"action=add but {rule['path']} already exists")
            rule_path.parent.mkdir(parents=True, exist_ok=True)
        else:  # edit
            if not rule_path.exists():
                raise ValueError(f"action=edit but {rule['path']} is missing")
        rule_path.write_text(rule["content"], encoding="utf-8")

        if delete_path and delete_path.exists():
            delete_path.unlink()

        props = LOOP12 / "proposals" / branch
        props.mkdir(parents=True, exist_ok=True)
        (props / "proposal.json").write_text(
            json.dumps(draft, indent=2, ensure_ascii=False), encoding="utf-8")
        pr_text = pr_markdown(draft)
        (props / "PR.md").write_text(pr_text, encoding="utf-8")
        # PR body also becomes the commit message; keep the scratch message
        # file OUTSIDE proposals/ so it never leaks into the PR's diff.
        BEATS_DIR.mkdir(exist_ok=True)
        title = pr_text.splitlines()[0].lstrip("# ").strip()
        msg_path = BEATS_DIR / f"commit-{branch}.msg"
        msg_path.write_text(f"{title}\n\n"
                            + (draft.get("pr", {}).get("body")
                               or draft.get("summary", ""))
                            + COMMIT_TRAILER + "\n", encoding="utf-8")

        git(["add", str(rule_path.relative_to(REPO_ROOT)).replace("\\", "/")])
        if delete_path:
            git(["add", "-A",
                 str(delete_path.relative_to(REPO_ROOT)).replace("\\", "/")])
        git(["add",
             str(props.relative_to(REPO_ROOT)).replace("\\", "/")])
        git(["commit", "-F", str(msg_path)])
        msg_path.unlink()
        git(["checkout", "main"])
    except BaseException:
        git(["checkout", "main"])
        git(["branch", "-D", branch])
        raise
    return branch


