MAX_ATTEMPTS = 2
COMMIT_TRAILER = "\nCo-Authored-By: Claude Code <noreply@anthropic.com>"
ENV = dict(os.environ)
ENV["CLAUDE_CODE_DISABLE_UNKNOWN_MODEL_WINDOW_ENFORCEMENT"] = "1"
ENV["CLAUDE_CODE_MAX_CONTEXT_TOKENS"] = "200000"

# --------------------------------------------------------------------------- #
# state (dreaming-state.md is the single source of truth)
# --------------------------------------------------------------------------- #

HEADER_RE = re.compile(r"^- \*\*(?P<key>[a-z_]+):\*\* (?P<val>.*)$")
LEDGER_ROW_RE = re.compile(r"^\| (\d+) \| (\d{4}-\d{2}-\d{2}) \| (\w+) \| "
                           r"([^ |]+) \| (.*) \|$")

STATE_DEFAULTS = {
    "state": "IDLE",          # IDLE | PROPOSED | NEEDS_HUMAN
    "run": 0,
    "last_dream": "2026-09-02",
    "branch": "—",
    "proposal": "—",
    "needs_human_note": "",
}

PROSE = """## What a dreaming beat is

A fresh engine reads the dated log entries and `progress.md` files the loops
left behind since `last_dream`, a deterministic scanner proves which
failure/correction signatures appear more than once, a **Dreamer** drafts the
smallest rule/skill improvement plus one deletion (both from the shared
`loopprojects/skills/` corpus), a **Checker** re-derives every citation, and
only on PASS the proposal is committed to a local `claude/dream-<run>` branch.
`last_dream` advances to today at the end of every completed beat.

_This file is generated by `dream.py` from its own state; do not hand-edit.
Rule changes never happen here - they live on a `claude/dream-<run>` branch
awaiting a human merge._"""


def read_state() -> dict:
    st = dict(STATE_DEFAULTS)          # parsed header values overwrite these
    st["ledger"] = []
    if STATE_MD.exists():
        for line in STATE_MD.read_text(encoding="utf-8").splitlines():
            m = HEADER_RE.match(line)
            if m:
                st[m.group("key")] = m.group("val")
            m2 = LEDGER_ROW_RE.match(line)
            if m2:
                st["ledger"].append({
                    "run": m2.group(1), "date": m2.group(2),
                    "state": m2.group(3), "branch": m2.group(4),
                    "what": m2.group(5),
                })
    st.setdefault("needs_human_note", "")
    return st


def _header_lines(st: dict) -> list[str]:
    return [
        f"- **state:** {st['state']}",
        f"- **run:** {st['run']}",
        f"- **last_dream:** {st['last_dream']}",
        f"- **branch:** {st['branch']}",
        f"- **proposal:** {st['proposal']}",
    ]


def write_state(st: dict) -> None:
    lines = [
        "# Dreaming state — Project 12 (The Dreaming Loop)",
        "",
        "The single source of truth for the dreaming loop. `dream.py` reads the",
        "header below to know where the last dream stopped, and rewrites it at",
        "the end of each beat. **Rule changes never happen in this file** — they",
        "live on a `claude/dream-<run>` branch awaiting a human merge; this file",
        "only records that the branch was proposed.",
        "",
        "## Header (machine-read; `- **key:** value` on the first lines)",
        "",
    ] + _header_lines(st) + ["", PROSE, "", "## Dream ledger", "",
                             "| Run | Date | State | Branch | What was proposed |",
                             "|-----|------|-------|--------|-------------------|"]
    for row in st["ledger"]:
        lines.append(f"| {row['run']} | {row['date']} | {row['state']} | "
                     f"{row['branch']} | {row['what']} |")
    lines.append("")
    STATE_MD.write_text("\n".join(lines), encoding="utf-8")


# --------------------------------------------------------------------------- #
# git / snapshot / headless-agent helpers
