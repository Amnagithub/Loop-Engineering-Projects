def record_usage(run: int, date: str, phase: str, attempt: int, usage,
                 result: str) -> None:
    if not USAGE_CSV.exists():
        USAGE_CSV.write_text(
            "run,date,phase,attempt,input_tokens,output_tokens,cache_read,result\n",
            encoding="utf-8")
    u = usage or {}
    with open(USAGE_CSV, "a", encoding="utf-8") as f:
        f.write(f"{run},{date},{phase},{attempt},{u.get('input', 0)},"
                f"{u.get('output', 0)},{u.get('cache_read', 0)},{result}\n")


def cost_summary() -> tuple[list, int, int, int, int]:
    rows = []
    if USAGE_CSV.exists():
        for line in USAGE_CSV.read_text(encoding="utf-8").splitlines()[1:]:
            parts = line.split(",")
            if len(parts) == 8:
                rows.append(parts)
    tot = {"input": 0, "output": 0, "cache": 0, "runs": 0}
    for r in rows:
        tot["input"] += int(r[4]); tot["output"] += int(r[5])
        tot["cache"] += int(r[6]); tot["runs"] += 1
    return rows, tot["input"], tot["output"], tot["cache"], tot["runs"]


def render_cost() -> str:
    rows, ti, to, tc, n = cost_summary()
    beats = {}
    for r in rows:
        beats.setdefault(r[0], []).append(r)
    body = [f"| Beat | Date | Input | Output | Cache-read | Agent runs |",
            "|------|------|-------|--------|------------|------------|"]
    for b in sorted(beats):
        rs = beats[b]
        body.append(f"| {b} | {rs[0][1]} | {sum(int(x[4]) for x in rs):,} | "
                    f"{sum(int(x[5]) for x in rs):,} | "
                    f"{sum(int(x[6]) for x in rs):,} | {len(rs)} |")
    return (f"# Cost of the dreaming loop — measured, not guessed\n\n"
            f"Each beat runs two fresh headless Claude agents (Dreamer + "
            f"Checker) whose token usage is captured from each `claude -p` "
            f"run JSON (see `runs/`). Numbers are **measured**, not modelled.\n\n"
            f"## Measured tokens per beat\n\n" + "\n".join(body) +
            f"\n\nTotals over {len(beats)} beat(s): **{ti:,} input + {to:,} "
            f"output tokens**; {n} agent runs.\n\n"
            f"Dollars = tokens × provider $/MTok / 1,000,000. The dominant "
            f"term is the per-invocation harness overhead, not the loop's own "
            f"content. This machine runs the loop's backend "
            f"(`ANTHROPIC_MODEL=deepseek-v4-flash`), so substitute that "
            f"provider's $/MTok for a real figure.\n")


def render_progress(st: dict) -> str:
    last = st["ledger"][-1] if st["ledger"] else None
    header = (f"# Progress — Project 12 (The Dreaming Loop)\n\n"
              f"The meta-loop: it dreams over the other loops' dated logs, "
              f"finds a failure/correction that appears more than once, and "
              f"proposes the smallest rule/skill improvement (plus one "
              f"deletion) on a `claude/dream-<run>` branch — never on main, "
              f"never merged without a human. This file is generated by "
              f"`dream.py`.\n\n## Last dream\n\n"
              f"- **Run:** {st['run']}\n- **Date:** {st['last_dream']}\n"
              f"- **State:** {st['state']}\n- **Branch:** {st['branch']}\n")
    if last:
        header += f"- **Proposal:** {last['what']}\n"
    header += f"\n## Needs human\n\n"
    if st["state"] == "NEEDS_HUMAN" and st.get("needs_human_note"):
        header += f"- {st['needs_human_note']}\n"
    else:
        header += "- _none — no dream is blocked on a person._\n"
    return header


def log_beat(st: dict, summary: str, result: str) -> None:
    if not LOG_MD.exists():
        LOG_MD.write_text(
            "# Loop log — Project 12 (The Dreaming Loop)\n\n"
            "| Run | Date | Result | What happened |\n"
            "|-----|------|--------|---------------|\n", encoding="utf-8")
    with open(LOG_MD, "a", encoding="utf-8") as f:
        f.write(f"| {st['run']} | {st['last_dream']} | {result} | "
                f"{summary} |\n")


