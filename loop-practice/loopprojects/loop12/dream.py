#!/usr/bin/env python3
"""loop12 dream.py - orchestrator of one Dreaming-Loop beat.

The Dreaming Loop is the META-loop: it reads the dated log entries and
progress files the other loops left behind, finds a failure or correction
that appears MORE THAN ONCE, and proposes the smallest possible change to the
SHARED rules (plus one deletion). It never changes the rules itself.

One beat, end to end:

    heartbeat -> clean-tree guard -> deterministic scan.py proves repeats
    (the ring that never lies) -> snapshot the repo at HEAD -> DREAMER
    (fresh headless claude) drafts the smallest rule/skill improvement +
    one deletion, citing real records -> CHECKER (fresh headless claude)
    re-derives every citation -> on PASS the proposal is committed to a local
    claude/dream-<run> branch ONLY (never main, never pushed) -> dreaming
    state advances -> the beat prints the exact git push + gh pr create
    one-liner for a human.

Nothing in the rules changes without a Pull Request and a human merge: the
engine never commits to main (it leaves the loop12 bookkeeping uncommitted
and prints the commit command), and the rule change exists only on the
claude/dream-<run> branch.

Usage (canonical interpreter: C:\\Python314\\python.exe; run from repo root):
    python loop12/dream.py --init
    python loop12/dream.py --date 2026-09-03   # one dreaming beat
    python loop12/dream.py --check             # run the scan only (no agents)
    python loop12/dream.py --show              # print the dreaming state
    python loop12/dream.py --reset             # clear NEEDS_HUMAN
"""

