# the beat
# --------------------------------------------------------------------------- #

def run_beat(claude: str, today: str, max_attempts: int) -> int:
    st = read_state()
    if st["state"] == "NEEDS_HUMAN":
        log_beat(st, "HOLD — dreaming loop is NEEDS_HUMAN: "
                     f"{st['needs_human_note'][:160]}", "HOLD")
        print(f"HOLD: state is NEEDS_HUMAN — {st['needs_human_note']}")
        return 0
    if st["branch"] not in ("—", ""):
        log_beat(st, f"HOLD — awaiting human merge of {st['branch']}", "HOLD")
        print(f"HOLD: proposal {st['branch']} is open; merge it, then --reset.")
        return 0

    clean, dirty = working_tree_clean()
    if not clean:
        print("Aborting: working tree is not clean. Commit or stash first:\n"
              + dirty)
        return 2

    after = st["last_dream"]
    if after >= today:
        print(f"Nothing newer than last dream ({after}) — already dreamed "
              f"through {after}.")
        return 0

    run = int(st["run"]) + 1
    scan = run_scan(after, today)
    run_dir = RUNS_DIR / f"dream-{run}"
    run_dir.mkdir(parents=True, exist_ok=True)
    (run_dir / "scan.json").write_text(json.dumps(scan, indent=2), encoding="utf-8")

    if not scan["clusters"]:
        # a beat can be a no-dream: nothing repeated is worth a rule
        st["run"] = run; st["last_dream"] = today
        st["state"] = "IDLE"; st["branch"] = "—"; st["proposal"] = "—"
        st["ledger"].append({"run": run, "date": today, "state": "IDLE",
                             "branch": "—",
                             "what": f"no repeat found in "
                                     f"{scan['records_in_window']} dated records"})
        write_state(st)
        PROGRESS_MD.write_text(render_progress(st), encoding="utf-8")
        COST_MD.write_text(render_cost(), encoding="utf-8")
        log_beat(st, f"no repeated failure/correction in the window "
                     f"({scan['records_in_window']} dated records)", "NO_REPEAT")
        print("No repeated failure/correction in the window — nothing to dream.")
        return 0

    # one fresh snapshot the agents work in (never the live tree)
    beat_tmp = make_snapshot()
    snap = beat_tmp / "snapshot"
    scan_json_path = beat_tmp / "scan.json"
    scan_json_path.write_text(json.dumps(scan, indent=2), encoding="utf-8")
    proposal_path = beat_tmp / "proposal.json"
    proposal_path.write_text("{}", encoding="utf-8")

    verdict = "FAIL"
    last_check = ""
    for attempt in range(1, max_attempts + 1):
        # DREAMER
        out = run_agent(claude, dreamer_prompt(run, scan_json_path,
                                               proposal_path, attempt,
                                               last_check),
                        run_dir / f"dreamer-a{attempt}.json", snap,
                        allowed="Read,Glob,Grep,Write")
        record_usage(run, today, "dreamer", attempt, out["usage"],
                     "OK" if out["ok"] else "ERR")
        try:
            draft = json.loads(proposal_path.read_text(encoding="utf-8"))
            if not draft or draft == {}:
                raise ValueError("empty proposal")
        except Exception:
            last_check = (f"The Dreamer did not write a valid proposal JSON to "
                          f"{proposal_path} (it must overwrite that file). "
                          + (out["err"] if out["err"] else ""))
            continue
        # CHECKER (fresh, read-only)
        ck = run_agent(claude, checker_prompt(scan_json_path, proposal_path),
                       run_dir / f"checker-a{attempt}.json", snap,
                       allowed="Read,Glob,Grep")
        verdict = parse_verdict(ck["text"])
        record_usage(run, today, "checker", attempt, ck["usage"], verdict)
        if verdict == "PASS":
            break
        last_check = ck["text"].strip() or "no text returned"
        print(f"  attempt {attempt}: Checker FAIL -> retrying Dreamer")

    if verdict != "PASS":
        st["state"] = "NEEDS_HUMAN"
        st["needs_human_note"] = (f"Dream {run} exhausted {max_attempts} "
                                  f"attempts. Last Checker: {last_check[:300]}")
        st["run"] = run                 # keep last_dream so a retry re-scans
        st["branch"] = "—"; st["proposal"] = "—"
        st["ledger"].append({"run": run, "date": today, "state": "NEEDS_HUMAN",
                             "branch": "—", "what": "Checker never PASSed"})
        write_state(st)
        PROGRESS_MD.write_text(render_progress(st), encoding="utf-8")
        COST_MD.write_text(render_cost(), encoding="utf-8")
        log_beat(st, "escalated — checker never PASSed", "ESCALATED")
        print(f"Escalated to NEEDS_HUMAN after {max_attempts} attempts.\n"
              f"Last Checker feedback:\n{last_check}")
        return 0

    # PASS -> apply to a claude/dream-<run> branch (never main)
    branch = apply_proposal(draft, run)
    props = LOOP12 / "proposals" / branch
    # keep a copy of the reviewed proposal on the main-side paper trail too
    (run_dir / "proposal.json").write_text(
        json.dumps(draft, indent=2, ensure_ascii=False), encoding="utf-8")
    (run_dir / "PR.md").write_text(pr_markdown(draft), encoding="utf-8")

    st["state"] = "PROPOSED"; st["run"] = run; st["last_dream"] = today
    st["branch"] = branch
    st["proposal"] = str((props / "PR.md").relative_to(LOOP12)).replace("\\", "/")
    what = (draft.get("pr", {}).get("title")
            or draft.get("repeated_failure", {}).get("theme", ""))[:160]
    st["ledger"].append({"run": run, "date": today, "state": "PROPOSED",
                         "branch": branch, "what": what})
    write_state(st)
    PROGRESS_MD.write_text(render_progress(st), encoding="utf-8")
    COST_MD.write_text(render_cost(), encoding="utf-8")
    log_beat(st, f"PROPOSED {branch} — {what}", "PROPOSED")

    print(_summary(st, draft, branch, props))
    return 0


def _summary(st: dict, draft: dict, branch: str, props: Path) -> str:
    rf = draft.get("repeated_failure", {})
    rc = draft.get("rule_change", {})
    dl = draft.get("deletion", {})
    pr = draft.get("pr", {})
    occ = rf.get("occurrences", [])
    s = []
    s.append("=" * 70)
    s.append(f"DREAMING BEAT {st['run']} ({st['last_dream']}) — PROPOSAL ON A "
             f"BRANCH")
    s.append("=" * 70)
    s.append(f"Repeated failure  : {rf.get('theme')}")
    s.append(f"  occurrences     : {len(occ)} dated records — " +
             ", ".join(f'{o.get("date")} {o.get("run")} {o.get("file")}:{o.get("line")}'
                       for o in occ))
    s.append(f"  how many times  : {rf.get('how_many_occurrences')}")
    s.append(f"Rule change       : {rc.get('action')} "
             f"{rc.get('path')} ({len(rc.get('content', ''))} chars)")
    s.append(f"Deletion          : {dl.get('path')} — {dl.get('reason')}")
    s.append("")
    s.append(f"The branch `{branch}` holds the rule change + PR body.")
    s.append("Rule files on `main` are UNCHANGED. Merge is a human step.")
    s.append("")
    s.append("Review + open the PR (local claude/ branch, never pushed):")
    s.append(f"  git push -u origin {branch}")
    s.append(f"  gh pr create --base main --head {branch} "
             f"--title {pr.get('title','')!r} --body-file "
             f"{LOOP12_REL}/proposals/{branch}/PR.md")
    s.append("")
    s.append("Commit the dreaming-loop bookkeeping on main (state/log/progress/"
             "cost/runs):")
    s.append(f"  git add {LOOP12_REL}")
    s.append(f"  git commit -m \"loop12: dream {st['run']} — {what_for(st, pr)}\"")
    s.append("")
    s.append("PR body preview (proposals/{}/PR.md):".format(branch))
    s.append(("-" * 70))
    s.append((pr.get("body") or "")[:1800])
    s.append(("-" * 70))
    return "\n".join(s)


def what_for(st: dict, pr: dict) -> str:
    t = (pr.get("title") or "propose smallest rule improvement")
    return t[:100]


